/**
 * Antigravity Siemens TIA Portal Openness & SimaticML Export Bridge
 * Generates:
 * - External SCL source files (.scl) with S7_Optimized_Access headers
 * - S7 DB source files (.db)
 * - S7 UDT source files (.udt)
 * - SimaticML XML for Ladder Blocks (SW.Blocks.CompileUnit with FlgNet)
 * - PLC_Tags.csv for TIA Portal Tag Table Import
 * - ImportToTiaPortal.cs C# Openness Automation Script
 */

import { useTagStore } from '../../stores/useTagStore'
import { useBlockStore } from '../../stores/useBlockStore'
import { useProjectStore } from '../../stores/useProjectStore'
import { useHardwareStore } from '../../stores/useHardwareStore'
import { LadBlockDefinition, LadNetwork } from '@shared/types/blocks'
import { LadderContactNode, LadderCoilNode } from '@shared/types/ladder'

export interface ExportFileItem {
  filename: string
  folder: string
  content: string
  type: 'scl' | 'db' | 'udt' | 'xml' | 'csv' | 'csharp'
}

export interface TiaExportBundle {
  targetCpu: string
  files: ExportFileItem[]
  summary: {
    sclFilesCount: number
    dbFilesCount: number
    udtFilesCount: number
    simaticMlBlocksCount: number
    totalTagsExported: number
  }
}

export class TiaExportBridge {
  public static generateBundle(): TiaExportBundle {
    const proj = useProjectStore.getState()
    const tags = useTagStore.getState()
    const blocks = useBlockStore.getState()
    const hw = useHardwareStore.getState()

    const files: ExportFileItem[] = []

    // 1. Generate SCL files
    for (const scl of blocks.sclBlocks) {
      const formattedScl = `{ S7_Optimized_Access := 'TRUE' }
VERSION : 0.1
// Generated by Antigravity Industrial PLC IDE
${scl.blockType === 'OB' ? 'ORGANIZATION_BLOCK' : scl.blockType === 'FB' ? 'FUNCTION_BLOCK' : 'FUNCTION'} "${scl.name}"
VAR_INPUT
END_VAR
VAR_OUTPUT
END_VAR
VAR_TEMP
END_VAR

BEGIN
${scl.code}
END_${scl.blockType === 'OB' ? 'ORGANIZATION_BLOCK' : scl.blockType === 'FB' ? 'FUNCTION_BLOCK' : 'FUNCTION'}
`
      files.push({
        filename: `${scl.name}.scl`,
        folder: 'ExternalSourceFiles',
        content: formattedScl,
        type: 'scl'
      })
    }

    // 2. Generate UDT files
    for (const udt of blocks.udts) {
      let udtScl = `TYPE "${udt.name}"
VERSION : 0.1
// S7 User Defined Type
STRUCT
`
      for (const m of udt.members) {
        udtScl += `    ${m.name} : ${m.dataType};${m.comment ? ' // ' + m.comment : ''}\n`
      }
      udtScl += `END_STRUCT;
END_TYPE
`
      files.push({
        filename: `${udt.name}.udt`,
        folder: 'PLC_Data_Types',
        content: udtScl,
        type: 'udt'
      })
    }

    // 3. Generate DB files
    for (const db of blocks.dataBlocks) {
      let dbScl = `DATA_BLOCK "${db.name}"
{ S7_Optimized_Access := '${db.optimizedAccess ? 'TRUE' : 'FALSE'}' }
VERSION : 0.1
// S7 Data Block
STRUCT
`
      for (const v of db.variables) {
        const init = v.defaultValue ? ` := ${v.defaultValue}` : ''
        dbScl += `    ${v.name} : ${v.dataType}${init};${v.comment ? ' // ' + v.comment : ''}\n`
      }
      dbScl += `END_STRUCT;
BEGIN
END_DATA_BLOCK
`
      files.push({
        filename: `${db.name}.db`,
        folder: 'ProgramBlocks',
        content: dbScl,
        type: 'db'
      })
    }

    // 4. Generate SimaticML XML for Ladder Blocks
    for (const lad of blocks.ladBlocks) {
      const xml = this.generateSimaticMlXml(lad)
      files.push({
        filename: `${lad.name}.simaticml.xml`,
        folder: 'SimaticML_Blocks',
        content: xml,
        type: 'xml'
      })
    }

    // 5. Generate PLC_Tags.csv (Siemens TIA Portal Standard Tag CSV format)
    let tagCsv = `Name,Path,Data Type,Logical Address,Comment\n`
    let totalTags = 0
    for (const tbl of tags.tagTables) {
      for (const t of tbl.tags) {
        tagCsv += `"${t.name}","${tbl.name}","${t.dataType}","${t.address}","${t.comment || ''}"\n`
        totalTags++
      }
    }
    files.push({
      filename: 'PLC_Tags.csv',
      folder: 'PLC_Tags',
      content: tagCsv,
      type: 'csv'
    })

    // 6. Generate C# TIA Portal Openness Automation Script
    const csharpScript = this.generateOpennessScript(proj.metadata?.targetCpu || 'S7-1200 CPU 1214C')
    files.push({
      filename: 'ImportToTiaPortal.cs',
      folder: 'OpennessScript',
      content: csharpScript,
      type: 'csharp'
    })

    return {
      targetCpu: proj.metadata?.targetCpu || 'SIMATIC S7-1200',
      files,
      summary: {
        sclFilesCount: blocks.sclBlocks.length,
        dbFilesCount: blocks.dataBlocks.length,
        udtFilesCount: blocks.udts.length,
        simaticMlBlocksCount: blocks.ladBlocks.length,
        totalTagsExported: totalTags
      }
    }
  }

  /**
   * Generates Siemens SimaticML XML Schema compliant AST for TIA Portal Openness
   */
  private static generateSimaticMlXml(lad: LadBlockDefinition): string {
    let compileUnits = ''

    for (const net of lad.networks) {
      let flgNetParts = ''

      if (net.nodes) {
        for (const node of net.nodes) {
          if (node.kind === 'contact') {
            const c = node as LadderContactNode
            const type = c.contactType === 'NC_CONTACT' ? 'ContactClosed' : 'ContactOpen'
            flgNetParts += `
        <Part Name="${type}" UId="${c.id}">
          <Symbol>
            <Component Name="${c.operand}" />
          </Symbol>
        </Part>`
          } else if (node.kind === 'coil') {
            const coil = node as LadderCoilNode
            const type = coil.coilType === 'SET_COIL' ? 'Set' : coil.coilType === 'RESET_COIL' ? 'Reset' : 'Coil'
            flgNetParts += `
        <Part Name="${type}" UId="${coil.id}">
          <Symbol>
            <Component Name="${coil.operand}" />
          </Symbol>
        </Part>`
          }
        }
      }

      compileUnits += `
    <SW.Blocks.CompileUnit ID="${net.networkNumber}" CompositionName="CompileUnits">
      <AttributeList>
        <NetworkSource>
          <FlgNet xmlns="http://www.siemens.com/automation/Openness/SW/NetworkSource/FlgNet/v4">
            <Parts>${flgNetParts}
            </Parts>
            <Wires>
              <Wire UId="W_PowerRail">
                <Powerrail />
                <NameCon UId="${net.nodes?.[0]?.id || 'N1'}" Name="in" />
              </Wire>
            </Wires>
          </FlgNet>
        </NetworkSource>
        <ProgrammingLanguage>LAD</ProgrammingLanguage>
      </AttributeList>
      <ObjectList>
        <MultilingualText ID="Title_${net.networkNumber}" CompositionName="Title">
          <ObjectList>
            <MultilingualTextItem ID="Title_Text_${net.networkNumber}" CompositionName="Items">
              <AttributeList>
                <Culture>en-US</Culture>
                <Text>${net.title || `Network ${net.networkNumber}`}</Text>
              </AttributeList>
            </MultilingualTextItem>
          </ObjectList>
        </MultilingualText>
      </ObjectList>
    </SW.Blocks.CompileUnit>`
    }

    return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by Antigravity Industrial PLC IDE - SimaticML Bridge -->
<Document>
  <Engineering version="V18" />
  <DocumentInfo>
    <Created>${new Date().toISOString()}</Created>
    <ExportSetting>WithDefaults</ExportSetting>
  </DocumentInfo>
  <SW.Blocks.OB ID="OB_${lad.name}">
    <AttributeList>
      <Name>${lad.name}</Name>
      <HeaderAuthor>Antigravity</HeaderAuthor>
      <HeaderVersion>0.1</HeaderVersion>
      <IsOptimized>true</IsOptimized>
    </AttributeList>
    <ObjectList>${compileUnits}
    </ObjectList>
  </SW.Blocks.OB>
</Document>`
  }

  /**
   * Generates C# Openness Automation Script
   */
  private static generateOpennessScript(targetCpu: string): string {
    return `// Siemens TIA Portal Openness Automatic Importer
// Generated by Antigravity Industrial PLC IDE
// Requires: Siemens.Engineering.dll (TIA Portal V17 / V18 / V19)

using System;
using System.IO;
using Siemens.Engineering;
using Siemens.Engineering.HW;
using Siemens.Engineering.SW;
using Siemens.Engineering.SW.Blocks;
using Siemens.Engineering.SW.Tags;

namespace Antigravity.TiaPortalBridge
{
    class Program
    {
        static void Main(string[] args)
        {
            Console.WriteLine("Connecting to SIMATIC TIA Portal Openness API...");

            using (TiaPortal tiaPortal = new TiaPortal(TiaPortalMode.WithUserInterface))
            {
                Project project = tiaPortal.Projects.Create(new DirectoryInfo(@"C:\\SiemensProjects"), "Antigravity_Export_Project");
                Console.WriteLine("Project Created: " + project.Name);

                // Add CPU Target: ${targetCpu}
                Device device = project.Devices.CreateWithItem("CPU1214C", "PLC_1", "OrderNumber:6ES7 214-1AG40-0XB0/V4.6");
                DeviceItem cpuItem = device.DeviceItems[1];
                PlcSoftware plcSoftware = cpuItem.GetService<SoftwareContainer>().Software as PlcSoftware;

                string exportDir = AppDomain.CurrentDomain.BaseDirectory;

                // 1. Import PLC Tags
                string tagCsv = Path.Combine(exportDir, "PLC_Tags", "PLC_Tags.csv");
                if (File.Exists(tagCsv))
                {
                    plcSoftware.TagTableGroup.TagTables.CreateFromFile("AntigravityTags", new FileInfo(tagCsv));
                    Console.WriteLine("Tags Imported successfully from CSV.");
                }

                // 2. Import External SCL Sources
                string sclDir = Path.Combine(exportDir, "ExternalSourceFiles");
                if (Directory.Exists(sclDir))
                {
                    foreach (var file in Directory.GetFiles(sclDir, "*.scl"))
                    {
                        var source = plcSoftware.ExternalSourceGroup.ExternalSources.CreateFromFile(Path.GetFileNameWithoutExtension(file), new FileInfo(file));
                        source.GenerateBlocksFromSource();
                        Console.WriteLine("Compiled SCL Block: " + Path.GetFileName(file));
                    }
                }

                // 3. Import SimaticML Blocks
                string xmlDir = Path.Combine(exportDir, "SimaticML_Blocks");
                if (Directory.Exists(xmlDir))
                {
                    foreach (var xmlFile in Directory.GetFiles(xmlDir, "*.xml"))
                    {
                        plcSoftware.BlockGroup.Blocks.Import(new FileInfo(xmlFile), ImportOptions.Override);
                        Console.WriteLine("Imported SimaticML Block: " + Path.GetFileName(xmlFile));
                    }
                }

                project.Save();
                Console.WriteLine("TIA Portal Project Import & Compilation Complete!");
            }
        }
    }
}
`
  }
}
