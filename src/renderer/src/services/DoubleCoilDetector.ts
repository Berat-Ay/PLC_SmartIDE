import { LadBlockDefinition, LadNetwork, BlockVariable, LadCoil } from '@shared/types/blocks'
import {
  LadderNetwork,
  LadderNode,
  LadderCoilNode,
  LadderSeriesNode,
  LadderContactNode
} from '@shared/types/ladder'
import { DiagnosticMessage } from '@shared/types/diagnostics'

export interface DoubleCoilConflict {
  operand: string
  normalizedOperand: string
  blockFileName: string
  blockName: string
  networkNumbers: number[]
  coilNodeIds: string[]
}

export class DoubleCoilDetector {
  /**
   * Extracts clean base operand name by stripping leading #, quotes, and any sequence of _Net\d+ suffixes.
   * e.g. "#MainConveyor_Run_Net1_Net3" -> "MainConveyor_Run"
   */
  public static getBaseOperandName(operand: string): string {
    if (!operand || typeof operand !== 'string') return ''
    let clean = operand.trim()
    clean = clean.replace(/^#/, '').replace(/"/g, '')
    // Iteratively strip any _Net\d+ suffixes
    while (/_Net\d+$/i.test(clean)) {
      clean = clean.replace(/_Net\d+$/i, '')
    }
    return clean.trim()
  }

  /**
   * Sanitizes base operand into a valid S7 variable identifier
   */
  public static getSanitizedVarName(operand: string): string {
    const base = this.getBaseOperandName(operand)
    const clean = base.replace(/[^a-zA-Z0-9_]/g, '_').replace(/^_+|_+$/g, '')
    return clean || 'Var'
  }

  /**
   * Scans a Ladder Block (or all active blocks) for double coil occurrences
   */
  public static detectConflicts(block: LadBlockDefinition): DoubleCoilConflict[] {
    return this.scanBlock(block)
  }

  public static scanBlock(block: LadBlockDefinition): DoubleCoilConflict[] {
    const operandToCoils = new Map<
      string,
      Array<{ networkNumber: number; coilId: string; rawOperand: string; isMergeNet: boolean }>
    >()

    const registerCoil = (operand: string, networkNumber: number, coilId: string, isMergeNet: boolean) => {
      if (!operand || !operand.trim()) return

      const trimmed = operand.trim()
      // Never flag intermediate temp coils (e.g. #MainConveyor_Run_Net1)
      if (trimmed.startsWith('#') && /_Net\d+$/i.test(trimmed)) {
        return
      }

      const normalized = this.getBaseOperandName(trimmed).toUpperCase()
      if (!normalized) return

      const list = operandToCoils.get(normalized) || []
      list.push({ networkNumber, coilId, rawOperand: trimmed, isMergeNet })
      operandToCoils.set(normalized, list)
    }

    const checkNode = (node: LadderNode, netNum: number, isMergeNet: boolean) => {
      if (node.kind === 'coil') {
        const c = node as LadderCoilNode
        // Only standard coils (--()-- and --(/)--) count as destructive double coils
        // Set (S) and Reset (R) coils on the same address are valid Siemens latching logic
        if (c.coilType === 'OUTPUT_COIL' || c.coilType === 'NEGATED_COIL') {
          registerCoil(c.operand, netNum, c.id, isMergeNet)
        }
      } else if (node.kind === 'parallel') {
        for (const branch of node.branches) {
          for (const subNode of branch) {
            checkNode(subNode, netNum, isMergeNet)
          }
        }
      }
    }

    for (const net of block.networks) {
      if (net.isSclNetwork) continue
      const isMerge = !!net.isAutoGeneratedMerge

      // Support Phase 2 nodes AST
      if (net.nodes && Array.isArray(net.nodes)) {
        for (const node of net.nodes) {
          checkNode(node, net.networkNumber, isMerge)
        }
      }

      // Also support Phase 1 elements
      if (net.elements && Array.isArray(net.elements)) {
        for (const el of net.elements) {
          if (el.kind === 'coil') {
            const c = el.data as { type: string; operand: string }
            if (c.type === 'COIL') {
              registerCoil(c.operand, net.networkNumber, el.id, isMerge)
            }
          }
        }
      }
    }

    const conflicts: DoubleCoilConflict[] = []
    for (const [normOp, list] of operandToCoils.entries()) {
      // Filter list: coils in non-merge networks
      const nonMergeList = list.filter((c) => !c.isMergeNet)
      const nonMergeNets = Array.from(new Set(nonMergeList.map((c) => c.networkNumber)))

      // Double-coil conflict only exists if:
      // 1) 2 or more distinct NON-MERGE networks drive this operand, OR
      // 2) At least 1 non-merge network drives this operand while a merge network also drives it (incomplete refactor)
      const hasMergeNet = list.some((c) => c.isMergeNet)
      const isConflicting = nonMergeNets.length >= 2 || (hasMergeNet && nonMergeNets.length >= 1)

      if (isConflicting) {
        const distinctNets = Array.from(new Set(list.map((c) => c.networkNumber)))
        const primaryCoil = nonMergeList[0] || list[0]
        conflicts.push({
          operand: primaryCoil.rawOperand,
          normalizedOperand: normOp,
          blockFileName: block.fileName,
          blockName: block.name,
          networkNumbers: distinctNets,
          coilNodeIds: list.map((c) => c.coilId)
        })
      }
    }

    return conflicts
  }

  /**
   * Generates diagnostic messages for all detected double-coils
   */
  public static generateDiagnostics(conflicts: DoubleCoilConflict[]): DiagnosticMessage[] {
    return conflicts.map((c) => ({
      id: `diag_double_coil_${c.blockFileName}_${c.normalizedOperand}`,
      severity: 'Warning',
      code: 'WARN_DOUBLE_COIL',
      source: 'Double-Coil Guard',
      message: `Double coil detected on "${c.operand}" in ${c.blockName} across Networks ${c.networkNumbers.join(
        ' & '
      )} — only the last evaluated network will control the physical state!`,
      targetFile: c.blockFileName,
      targetSymbol: c.operand,
      autoFixable: true,
      fixAction: 'AUTO_ASSIGN_ADDRESS',
      fixLabel: 'Auto-Merge Coils',
      timestamp: Date.now()
    }))
  }

  /**
   * 1-Click Auto-Refactor (Solution A):
   * Converts double coils into intermediate variables and generates/updates a single consolidated OR output mapping network.
   * Completely idempotent: clicking repeatedly will never create _Net1_Net1 chains or duplicate networks.
   */
  public static autoRefactorBlock(block: LadBlockDefinition, conflictOperand?: string): LadBlockDefinition {
    let targetOperand = conflictOperand
    if (!targetOperand) {
      const conflicts = this.scanBlock(block)
      if (conflicts.length === 0) return block
      targetOperand = conflicts[0].operand
    }

    const baseOperand = this.getBaseOperandName(targetOperand)
    if (!baseOperand) return block
    const sanitizedVarBase = this.getSanitizedVarName(targetOperand)
    const normTarget = baseOperand.toUpperCase()

    // Find all networks driving this base operand (excluding existing auto-generated merge networks)
    const conflictingNetNumbers: number[] = []
    for (const net of block.networks) {
      if (net.isAutoGeneratedMerge) continue

      const hasCoil =
        (net.nodes || []).some((n) => {
          if (n.kind !== 'coil') return false
          const c = n as LadderCoilNode
          return (
            (c.coilType === 'OUTPUT_COIL' || c.coilType === 'NEGATED_COIL') &&
            this.getBaseOperandName(c.operand).toUpperCase() === normTarget
          )
        }) ||
        (net.elements || []).some((el) => {
          if (el.kind !== 'coil') return false
          const c = el.data as LadCoil
          return (
            (c.type === 'COIL') &&
            this.getBaseOperandName(c.operand).toUpperCase() === normTarget
          )
        })

      if (hasCoil && !conflictingNetNumbers.includes(net.networkNumber)) {
        conflictingNetNumbers.push(net.networkNumber)
      }
    }

    if (conflictingNetNumbers.length === 0) {
      return block
    }

    conflictingNetNumbers.sort((a, b) => a - b)

    // Build intermediate variable names using clean sanitized base name (e.g. MainConveyor_Run_Net1, MainConveyor_Run_Net3)
    const intermediateVarNames: string[] = []
    let updatedNetworks = [...block.networks]

    for (const netNum of conflictingNetNumbers) {
      const intermediateName = `${sanitizedVarBase}_Net${netNum}`
      if (!intermediateVarNames.includes(intermediateName)) {
        intermediateVarNames.push(intermediateName)
      }

      const netIdx = updatedNetworks.findIndex((n) => n.networkNumber === netNum)
      if (netIdx !== -1) {
        const net = updatedNetworks[netIdx]
        if (net.isAutoGeneratedMerge) continue

        // Replace coils in Phase 2 nodes
        if (net.nodes) {
          const replaceInNodes = (nodes: LadderSeriesNode[]): LadderSeriesNode[] => {
            return nodes.map((n) => {
              if (
                n.kind === 'coil' &&
                (n as LadderCoilNode).coilType !== 'SET_COIL' &&
                (n as LadderCoilNode).coilType !== 'RESET_COIL' &&
                this.getBaseOperandName((n as LadderCoilNode).operand).toUpperCase() === normTarget
              ) {
                return {
                  ...n,
                  operand: `#${intermediateName}`,
                  symbolName: intermediateName,
                  comment: `Auto-refactored intermediate coil for Net ${netNum}`
                } as LadderCoilNode
              } else if (n.kind === 'parallel') {
                return {
                  ...n,
                  branches: n.branches.map(replaceInNodes)
                }
              }
              return n
            })
          }
          updatedNetworks[netIdx] = {
            ...net,
            nodes: replaceInNodes(net.nodes)
          }
        }

        // Replace coils in Phase 1 elements
        if (net.elements) {
          updatedNetworks[netIdx] = {
            ...updatedNetworks[netIdx],
            elements: net.elements.map((el) => {
              if (
                el.kind === 'coil' &&
                this.getBaseOperandName((el.data as LadCoil).operand).toUpperCase() === normTarget
              ) {
                return {
                  ...el,
                  data: {
                    ...(el.data as LadCoil),
                    operand: `#${intermediateName}`
                  }
                }
              }
              return el
            })
          }
        }
      }
    }

    // Add intermediate variables to interface (deduplicated)
    const section: 'temp' | 'static' = block.blockType === 'FB' ? 'static' : 'temp'
    const existingVarNames = new Set(block.interface[section].map((v) => v.name.toUpperCase()))
    const newVars: BlockVariable[] = []

    for (const name of intermediateVarNames) {
      if (!existingVarNames.has(name.toUpperCase())) {
        newVars.push({
          id: `v_automerge_${name}_${Date.now()}`,
          name,
          dataType: 'BOOL',
          defaultValue: 'FALSE',
          retain: false,
          accessibleFromHMI: true,
          comment: `Auto-refactored intermediate condition for ${baseOperand}`
        })
        existingVarNames.add(name.toUpperCase())
      }
    }

    const updatedInterface = {
      ...block.interface,
      [section]: [...block.interface[section], ...newVars]
    }

    // Build or update the single consolidated OR output mapping network
    const parallelBranches: LadderSeriesNode[][] = intermediateVarNames.map((name, i) => [
      {
        id: `node_or_${sanitizedVarBase}_${i}_${Date.now()}`,
        kind: 'contact',
        contactType: 'NO_CONTACT',
        operand: `#${name}`,
        symbolName: name,
        comment: `Condition from Net ${conflictingNetNumbers[i] || i + 1}`
      } as LadderContactNode
    ])

    const outputCoil: LadderCoilNode = {
      id: `node_out_${sanitizedVarBase}_${Date.now()}`,
      kind: 'coil',
      coilType: 'OUTPUT_COIL',
      operand: baseOperand,
      comment: `Consolidated physical output for ${baseOperand}`
    }

    const existingMergeIdx = updatedNetworks.findIndex(
      (n) =>
        n.isAutoGeneratedMerge &&
        (n.mergedOperand?.toUpperCase() === normTarget ||
          this.getBaseOperandName(n.title).toUpperCase() === normTarget)
    )

    if (existingMergeIdx !== -1) {
      // UPDATE in place! Never spawn duplicate networks!
      const existingNet = updatedNetworks[existingMergeIdx]
      updatedNetworks[existingMergeIdx] = {
        ...existingNet,
        isAutoGeneratedMerge: true,
        mergedOperand: baseOperand,
        title: `[Auto-Generated] Output Mapping: ${baseOperand}`,
        comment: `Consolidated OR-mapping across Networks ${conflictingNetNumbers.join(' & ')}`,
        nodes: [
          {
            id: `node_parallel_merge_${Date.now()}`,
            kind: 'parallel',
            branches: parallelBranches
          },
          outputCoil
        ]
      }
    } else {
      // Append single new consolidated network
      const nextNetworkNumber = updatedNetworks.length + 1
      const mappingNetwork: LadNetwork = {
        id: `net_merge_${sanitizedVarBase}_${Date.now()}`,
        networkNumber: nextNetworkNumber,
        title: `[Auto-Generated] Output Mapping: ${baseOperand}`,
        comment: `Consolidated OR-mapping across Networks ${conflictingNetNumbers.join(' & ')}`,
        isAutoGeneratedMerge: true,
        mergedOperand: baseOperand,
        nodes: [
          {
            id: `node_parallel_merge_${Date.now()}`,
            kind: 'parallel',
            branches: parallelBranches
          },
          outputCoil
        ]
      }
      updatedNetworks.push(mappingNetwork)
    }

    // Deduplicate any lingering duplicate merge networks from past runs
    let seenMerge = false
    updatedNetworks = updatedNetworks.filter((n) => {
      if (
        n.isAutoGeneratedMerge &&
        (n.mergedOperand?.toUpperCase() === normTarget ||
          this.getBaseOperandName(n.title).toUpperCase() === normTarget)
      ) {
        if (seenMerge) return false
        seenMerge = true
      }
      return true
    })

    // Re-index network numbers sequentially 1..N
    updatedNetworks = updatedNetworks.map((net, idx) => ({
      ...net,
      networkNumber: idx + 1
    }))

    return {
      ...block,
      interface: updatedInterface,
      networks: updatedNetworks
    }
  }
}
