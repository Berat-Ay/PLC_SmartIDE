import { LadderSeriesNode } from './ladder'

export type BlockType = 'OB' | 'FB' | 'FC' | 'DB'
export type BlockLanguage = 'LAD' | 'SCL' | 'DB'
export type BlockSection = 'Input' | 'Output' | 'InOut' | 'Static' | 'Temp' | 'Constant'

export interface BlockVariable {
  id: string
  name: string
  dataType: string // primitive or UDT reference
  defaultValue?: string
  retain: boolean
  accessibleFromHMI: boolean
  comment?: string
  calculatedOffset?: string // S7 Standard Access Byte.Bit (e.g. 0.0, 2.0, 6.0)
  members?: BlockVariable[] // Only for dataType 'Struct'
}

export interface BlockInterface {
  input: BlockVariable[]
  output: BlockVariable[]
  inOut: BlockVariable[]
  static: BlockVariable[] // Only FB has static instance memory
  temp: BlockVariable[]
  constant: BlockVariable[]
}

// Ladder Logic AST Schema (Structured for Phase 2 visual LAD grid & SVG ladder engine)
export interface LadContact {
  type: 'NO' | 'NC' | 'POS_EDGE' | 'NEG_EDGE'
  operand: string // Tag or address (e.g. "Pump1_StartCmd" or "%I0.0")
}

export interface LadCoil {
  type: 'COIL' | 'SET' | 'RESET'
  operand: string
}

export interface LadBox {
  type: 'BOX'
  boxType: 'TON' | 'TOF' | 'MOVE' | 'ADD' | 'SUB' | 'CMP_EQ' | 'CMP_GT' | 'FB_CALL' | 'NORM_X' | 'SCALE_X'
  instanceDbName?: string
  parameters: Record<string, string>
}

export interface LadElement {
  id: string
  kind: 'contact' | 'coil' | 'box'
  data: LadContact | LadCoil | LadBox
}

export interface LadNetwork {
  id?: string
  networkNumber: number
  title: string
  comment?: string
  isSclNetwork?: boolean
  sclCode?: string
  elements?: LadElement[]
  nodes?: LadderSeriesNode[]
  isAutoGeneratedMerge?: boolean
  mergedOperand?: string
}

export interface LadBlockDefinition {
  blockType: 'OB' | 'FB' | 'FC'
  blockNumber: number
  name: string
  fileName: string // e.g. OB1_Main.lad.json
  optimizedAccess: boolean
  interface: BlockInterface
  networks: LadNetwork[]
  schemaVersion: string
}

export interface SclBlockDefinition {
  blockType: 'OB' | 'FB' | 'FC'
  blockNumber: number
  name: string
  fileName: string // e.g. OB30_PID_Cycle.scl
  optimizedAccess: boolean
  interface: BlockInterface
  code: string
}

export type DbType = 'Global' | 'Instance'

export interface DataBlockDefinition {
  id?: string
  blockType: 'DB'
  blockNumber: number
  name: string
  fileName: string // e.g. DB1_PlantData.db.json
  dbType: DbType
  parentFbId?: string
  parentFbName?: string
  optimizedAccess: boolean
  variables: BlockVariable[]
  comment?: string
}

export type ProgramBlock = LadBlockDefinition | SclBlockDefinition | DataBlockDefinition
