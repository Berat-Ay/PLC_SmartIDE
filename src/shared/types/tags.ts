import { S7DataType } from './s7types'

export interface TagDefinition {
  id: string
  name: string
  dataType: S7DataType
  address: string // e.g. %M0.0, %MW10, %I0.0
  comment?: string
  systemLocked?: boolean // e.g., Clock or System memory tags generated by CPU
  monitorValue?: string | number | boolean
}

export interface TagTable {
  id: string
  name: string
  fileName: string // e.g. 'default_tags.tags.json'
  tags: TagDefinition[]
}

export interface TagMemoryCollision {
  tagId: string
  tagName: string
  address: string
  conflictsWith: Array<{
    type: 'Tag' | 'ClockMemory' | 'SystemMemory' | 'HardwareIO'
    id: string
    name: string
    address: string
    overlapArea: string // e.g. "Byte 11" or "Byte 10, Bit 2"
  }>
}
